export default function AdminTableScreen() {
  const { naam } = useLocalSearchParams<{ naam: string }>();
  const { isOwner } = useAuth();
  const config = CONFIGS[naam ?? ''];
  if (!config) return <Empty title="Onbekend onderdeel" />;
  return (
    <>
      <Stack.Screen options={{ title: config.title }} />
      <AdminTable config={config} canWrite={config.ownerOnly ? isOwner : true} />
    </>
  );
}
